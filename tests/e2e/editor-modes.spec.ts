async function start(profile: string) {
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((item): item is [string, string] => item[1] !== undefined)), ASTRO_DESKTOP_USER_DATA: profile }
  delete env.ELECTRON_RUN_AS_NODE
  delete env.ELECTRON_RENDERER_URL
  const app = await electron.launch({ args: [path.resolve('.')], env })
  const page = await app.firstWindow()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  return { app, page, errors }
}

async function launch(blog: string, profile: string) {
  const session = await start(profile)
  await session.app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, blog)
  await session.page.getByRole('button', { name: '选择博客目录', exact: true }).click()
  return session
}

async function showSourceEnd(page: Page) {
  await page.locator('.cm-scroller').evaluate(element => { element.scrollTop = element.scrollHeight })
}

async function closeApp(app: ElectronApplication, root: string, prefix: string) {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())).catch(() => undefined)
  await app.close()
  if (path.resolve(root).startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(root).startsWith(prefix)) await rm(root, { recursive: true, force: true, maxRetries: 8, retryDelay: 50 })
}

