import { test, expect, _electron as electron, type Page } from '@playwright/test'
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

const longCategory = '这是一个非常非常长的中文分类名称用于检查窄窗口里不会被截断或合并'

function article(title: string, fields: string): string {
  return `---\ntitle: ${title}\npublished: 2026-01-01\n${fields}---\n正文\n`
}

test('article statistics follow content directories and open the same lists', async ({}, testInfo) => {
  test.setTimeout(180000)
  const root = await mkdtemp(path.join(tmpdir(), 'astro-stats-e2e-'))
  const blog = path.join(root, '中文 统计博客')
  const other = path.join(root, '另一 统计博客')
  const posts = path.join(blog, 'src/contents/post')
  const drafts = path.join(blog, 'src/contents/drafts')
  await mkdir(posts, { recursive: true })
  await mkdir(drafts, { recursive: true })
  await mkdir(path.join(blog, 'src/contents/ai-daily'), { recursive: true })
  await mkdir(path.join(other, 'src/contents/post'), { recursive: true })
  await mkdir(path.join(other, 'src/contents/ai-daily'), { recursive: true })
  await writeFile(path.join(blog, 'package.json'), JSON.stringify({ dependencies: { astro: '^5.3.0' } }))
  await writeFile(path.join(other, 'package.json'), JSON.stringify({ dependencies: { astro: '^5.3.0' } }))
  await writeFile(path.join(posts, '甲.md'), article('甲', 'draft: true\ncategory: 前端\ntags: [Astro, Astro]\n'))
  await writeFile(path.join(posts, '乙.md'), article('乙', 'category: 笔记\ntags: [astro]\n'))
  await writeFile(path.join(posts, '名称未分类.md'), article('名称未分类', 'category: "未分类"\ntags: ["未分类"]\n'))
  await writeFile(path.join(posts, '长分类.md'), article('长分类', `category: "${longCategory}"\ntags: ["补充"]\n`))
  for (const name of ['分类一', '分类二', '分类三', '分类四']) {
    await writeFile(path.join(posts, `${name}.md`), article(name, `category: ${name}\ntags: ["补充"]\n`))
  }
  await writeFile(path.join(posts, '坏.md'), '这不是 frontmatter\n')
  await writeFile(path.join(drafts, '丙.md'), article('丙', 'draft: false\ncategory: 前端\n'))
  await writeFile(path.join(drafts, '丁.md'), article('丁', 'tags: [Astro]\n'))
  await writeFile(path.join(drafts, '无效分类.md'), article('无效分类', 'category: 1\ntags: [笔记]\n'))
  await writeFile(path.join(drafts, '无效标签.md'), article('无效标签', 'category: 生活\ntags: 不是数组\n'))
  await writeFile(path.join(blog, 'src/contents/ai-daily/日报.md'), '---\ntitle: 日报\npublished: 2026-02-01\nsummary: 摘要\ntags: [Astro]\ndraft: true\n---\n日报正文\n')
  await writeFile(path.join(other, 'src/contents/post/唯一.md'), article('唯一', 'category: 其他\ntags: [其他]\n'))
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), ASTRO_DESKTOP_USER_DATA: path.join(root, 'profile') }
  delete env.ELECTRON_RUN_AS_NODE
  delete env.ELECTRON_RENDERER_URL
  const app = await electron.launch({ args: [path.resolve('.')], env })
  const page = await app.firstWindow()
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  try {
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, blog)
    await page.getByRole('button', { name: '选择博客目录', exact: true }).click()
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toBeVisible()
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await expect(page.getByRole('region', { name: '文章统计', exact: true })).toBeVisible()
    await expect(page.locator('.stats-meta')).toContainText('中文 统计博客')
    await expect(page.getByRole('button', { name: '查看正文，8 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看草稿，4 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看 AI 日报，1 篇', exact: true })).toBeVisible()
    await expect(page.locator('.stats-scope')).toContainText('不含 AI 日报')
    await expect(page.locator('.stats-scope')).toContainText('无标签 1 篇')
    await expect(page.getByRole('button', { name: '分类 前端，2 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '标签 Astro，2 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '标签 astro，1 篇', exact: true })).toBeVisible()
    await expect(page.locator('.stats-exceptions')).toContainText('读取失败 1 项')
    await expect(page.locator('.stats-exceptions')).toContainText('坏.md')
    await expect(page.locator('.stats-exceptions')).toContainText('category 不是字符串')
    await expect(page.locator('.stats-exceptions')).toContainText('tags 不是字符串数组')
    await expect(page.getByRole('region', { name: '分类排行', exact: true })).toContainText('共 10 项')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 680))
    await page.locator('.stats-page').evaluate(element => { element.scrollTop = 0 })
    await page.screenshot({ path: testInfo.outputPath('stats-light.png'), animations: 'disabled' })
    await page.screenshot({ path: path.resolve('docs/images/stats-light.png'), animations: 'disabled' })
    await page.getByRole('link', { name: '项目设置', exact: true }).click()
    await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
    await page.goBack()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await page.screenshot({ path: testInfo.outputPath('stats-dark.png'), animations: 'disabled' })
    await page.screenshot({ path: path.resolve('docs/images/stats-dark.png'), animations: 'disabled' })
    await page.getByRole('link', { name: '项目设置', exact: true }).click()
    await page.getByRole('button', { name: '切换浅色主题', exact: true }).click()
    await page.goBack()
    await expect(page.getByRole('region', { name: '分类排行', exact: true })).not.toContainText('不是只显示前几项')
    await page.getByRole('button', { name: '下一页分类', exact: true }).click()
    await expect(page.getByRole('region', { name: '分类排行', exact: true })).toContainText('第 2 / 2 页，共 10 项')
    await page.getByLabel('搜索分类', { exact: true }).fill(longCategory)
    await expect(page.getByRole('button', { name: `分类 ${longCategory}，1 篇`, exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '分类 前端，2 篇', exact: true })).toHaveCount(0)
    await page.getByLabel('搜索分类', { exact: true }).fill('未分类')
    await expect(page.getByRole('button', { name: '分类 未分类，1 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '分类 未分类，没有填写 category，1 篇', exact: true })).toBeVisible()
    await page.getByLabel('搜索分类', { exact: true }).fill('')
    await page.getByRole('button', { name: '查看正文，8 篇', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/#\/library\/posts$/)
    await expect(page.locator('.filter-total')).toHaveText('8 篇内容')
    await expect(page.getByRole('heading', { name: '正文' })).toContainText('8')
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：丙', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '查看文章：日报', exact: true })).toHaveCount(0)
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByRole('button', { name: '查看草稿，4 篇', exact: true }).click()
    await expect(page).toHaveURL(/#\/library\/drafts$/)
    await expect(page.locator('.filter-total')).toHaveText('4 篇内容')
    await expect(page.getByRole('button', { name: '查看文章：丙', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：丁', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toHaveCount(0)
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByRole('button', { name: '查看 AI 日报，1 篇', exact: true }).click()
    await expect(page.locator('.filter-total')).toHaveText('1 篇内容')
    await expect(page.getByRole('button', { name: '查看文章：日报', exact: true })).toBeVisible()
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByRole('button', { name: '分类 前端，2 篇', exact: true }).click()
    await expect(page).toHaveURL(/#\/library\/writing$/)
    await expect(page.locator('.filter-total')).toHaveText('2 篇内容')
    await expect(page.getByRole('heading', { name: '正文和草稿' })).toContainText('2')
    await expect(page.locator('.article-row')).toHaveCount(2)
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：丙', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：日报', exact: true })).toHaveCount(0)
    await expect(page.getByLabel('按分类筛选', { exact: true })).toHaveValue(`name:${encodeURIComponent('前端')}`)
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await expect(page.locator('.filter-total')).toHaveText('12 篇内容')
    await expect(page.getByLabel('按分类筛选', { exact: true })).toHaveValue('')
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByRole('button', { name: '标签 Astro，2 篇', exact: true }).click()
    await expect(page.locator('.filter-total')).toHaveText('2 篇内容')
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：丁', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：乙', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '查看文章：日报', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByRole('button', { name: '查看无标签的正文和草稿', exact: true }).click()
    await expect(page.locator('.filter-total')).toHaveText('1 篇内容')
    await expect(page.getByRole('button', { name: '查看文章：丙', exact: true })).toBeVisible()
    await expect(page.locator('.article-row')).toHaveCount(1)
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await page.getByLabel('搜索分类', { exact: true }).fill('未分类')
    await page.getByRole('button', { name: '分类 未分类，没有填写 category，1 篇', exact: true }).click()
    await expect(page.locator('.filter-total')).toHaveText('1 篇内容')
    await expect(page.getByRole('button', { name: '查看文章：丁', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：名称未分类', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '查看文章：无效分类', exact: true })).toHaveCount(0)
    await page.locator('a[href="#/library/drafts"]').click()
    // 直接写入文件（外部修改），刷新后统计更新
    await writeFile(path.join(drafts, '丙.md'), article('丙', 'draft: false\ncategory: "新分类"\n'))
    // 刷新文章列表，等待刷新完成（按钮重新启用）
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    await expect(page.getByRole('button', { name: '刷新文章', exact: true })).toBeEnabled()
    expect(await readFile(path.join(drafts, '丙.md'), 'utf8')).toContain('category: "新分类"')
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await expect(page.getByRole('button', { name: '分类 前端，1 篇', exact: true })).toBeVisible()
    // 刷新后新增的「新分类」在第 2 页，需搜索过滤后才在第 1 页可见
    await page.getByLabel('搜索分类', { exact: true }).fill('新分类')
    await expect(page.getByRole('button', { name: '分类 新分类，1 篇', exact: true })).toBeVisible()
    await page.getByLabel('搜索分类', { exact: true }).fill('')
    await page.getByRole('button', { name: '查看草稿，4 篇', exact: true }).click()
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    const modal = page.getByRole('dialog', { name: '创建新文章' })
    await modal.getByLabel('文章标题').fill('统计新建')
    await modal.getByLabel('分类', { exact: false }).fill('前端')
    await modal.getByRole('button', { name: '创建草稿', exact: true }).click()
    await expect(page).toHaveURL(/#\/library\/drafts$/)
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await expect(page.getByRole('button', { name: '查看草稿，5 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '分类 前端，2 篇', exact: true })).toBeVisible()
    const external = path.join(posts, '外部新增.md')
    await writeFile(external, article('外部新增', 'category: 笔记\ntags: [Astro]\n'))
    await expect(page.getByRole('button', { name: '查看正文，8 篇', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    await expect(page.getByRole('button', { name: '查看正文，9 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '标签 Astro，3 篇', exact: true })).toBeVisible()
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, other)
    await page.getByRole('button', { name: '打开项目', exact: true }).click()
    await expect(page.getByRole('button', { name: '查看文章：唯一', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看文章：甲', exact: true })).toHaveCount(0)
    await page.getByRole('link', { name: '文章统计', exact: true }).click()
    await expect(page.locator('.stats-meta')).toContainText(other)
    await expect(page.locator('.stats-meta')).not.toContainText('中文 统计博客')
    await expect(page.getByRole('button', { name: '查看正文，1 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看草稿，0 篇', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '查看 AI 日报，0 篇', exact: true })).toBeVisible()
    await expect(page.locator('.stats-exceptions')).toContainText('草稿目录 src/contents/drafts 不存在')
    await expect(page.getByRole('button', { name: '查看正文，9 篇', exact: true })).toHaveCount(0)
    expect(pageErrors).toEqual([])
  } finally {
    await app.close()
    const target = path.resolve(root)
    if (target.startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(target).startsWith('astro-stats-e2e-')) await rm(target, { recursive: true, force: true })
  }
})
