import { test, expect, _electron as electron, type Page } from '@playwright/test'
import { mkdtemp, mkdir, readFile, writeFile, rm, unlink } from 'node:fs/promises'
import path from 'node:path'
import { tmpdir } from 'node:os'

test('editor saves real files, guards navigation, detects conflicts and restores after window loss', async ({}, testInfo) => {
  const root = await mkdtemp(path.join(tmpdir(), 'astro-editor-e2e-'))
  const blog = path.join(root, '中文 博客'), relative = 'src/contents/post/编辑.md', file = path.join(blog, relative)
  await mkdir(path.dirname(file), { recursive: true }); await mkdir(path.join(blog, 'src/contents/ai-daily'), { recursive: true })
  await writeFile(path.join(blog, 'package.json'), JSON.stringify({ dependencies: { astro: '^5.3.0' } }))
  const original = '---\r\n# 注释\r\ntitle: 编辑测试\r\npublished: 2026-01-01\r\ndraft: true\r\ncategory: 测试\r\ntags: [Astro]\r\nextra: keep\r\n---\r\n# 标题\r\n\r\n原始正文\r\n'
  await writeFile(file, original)
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((item): item is [string, string] => item[1] !== undefined)), ASTRO_DESKTOP_USER_DATA: path.join(root, 'profile') }
  delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL
  let app = await electron.launch({ args: [path.resolve('.')], env })
  let page = await app.firstWindow()
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  const append = async (page: Page, text: string) => {
    const editor = page.getByLabel('文章源码编辑器')
    await expect(editor).toHaveAttribute('contenteditable', 'true')
    await editor.click(); await editor.press('Control+End')
    for (const [index, line] of text.split('\n').entries()) {
      if (index) await page.keyboard.press('Enter')
      if (line) await page.keyboard.insertText(line)
    }
  }
  try {
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, blog)
    await page.getByRole('button', { name: '选择博客目录', exact: true }).click()
    await page.getByRole('button', { name: '查看文章：编辑测试', exact: true }).click()
    await append(page, '撤销检查')
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await expect(page.locator('.editor-save-state')).toHaveText('已保存')
    await page.getByRole('button', { name: '重做', exact: true }).click()
    await expect(page.locator('.editor-save-state')).toHaveText('未保存')
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await append(page, '\n## 新内容\n**保存测试**\n')
    await expect(page.locator('.editor-save-state')).toHaveText('未保存')
    await page.getByRole('tab', { name: '左右分栏', exact: true }).click()
    await expect(page.getByRole('heading', { name: '新内容', exact: true })).toBeVisible()
    await page.getByRole('separator').press('ArrowRight')
    await expect(page.getByRole('separator')).toHaveAttribute('aria-valuenow', '55')
    await page.getByRole('tab', { name: '预览', exact: true }).click()
    await expect(page.getByLabel('文章源码编辑器')).not.toBeVisible()
    await page.getByRole('tab', { name: '预览', exact: true }).press('Control+s')
    await expect(page.locator('.editor-save-state')).toHaveText('已保存')
    const saved = original + '\r\n## 新内容\r\n**保存测试**\r\n'
    expect(await readFile(file, 'utf8')).toBe(saved)
    await page.getByRole('tab', { name: '左右分栏', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('editor-split-light.png'), animations: 'disabled' })
    await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await page.screenshot({ path: testInfo.outputPath('editor-split-dark.png'), animations: 'disabled' })
    await append(page, '未保存导航')
    await page.locator('a[href="#/settings"]').click()
    const leave = page.getByRole('dialog', { name: '文章有未保存的修改' })
    await expect(leave).toBeVisible(); await leave.getByRole('button', { name: '取消', exact: true }).click()
    await expect(page.getByRole('region', { name: '文章编辑工作区' })).toBeVisible()
    // Native close must use the same guard.
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
    await expect(leave).toBeVisible(); await leave.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await leave.getByRole('button', { name: '放弃修改', exact: true }).click()
    expect(await readFile(file, 'utf8')).toBe(saved)
    await page.getByRole('button', { name: '查看文章：编辑测试', exact: true }).click()
    await append(page, '冲突中的编辑')
    await writeFile(file, saved + '来自外部编辑器')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(page.locator('.editor-error')).toContainText('其他程序修改')
    await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await leave.getByRole('button', { name: '保存并继续', exact: true }).click()
    await expect(leave).not.toBeVisible()
    await expect(page.locator('.editor-error')).toContainText('其他程序修改')
    expect(await readFile(file, 'utf8')).toBe(saved + '来自外部编辑器')
    const copy = path.join(root, '编辑副本.md')
    await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }) }, copy)
    await page.getByRole('button', { name: '另存编辑副本', exact: true }).click()
    await expect(page.locator('.editor-footer')).toContainText('副本已写入')
    expect(await readFile(copy, 'utf8')).toBe(saved + '冲突中的编辑')
    await page.getByRole('button', { name: '重新加载磁盘版本', exact: true }).click()
    await page.getByRole('button', { name: '保留编辑并加载', exact: true }).click()
    await expect(page.locator('.editor-save-state')).toHaveText('已保存')
    await page.getByRole('button', { name: /恢复记录 \(/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: new RegExp(relative) }).click()
    await expect(page.getByLabel('恢复记录源码')).toHaveValue(saved.replace(/\r\n/g, '\n') + '冲突中的编辑')
    await page.getByRole('button', { name: '打开原文章', exact: true }).click()
    await page.getByRole('button', { name: '恢复到编辑器', exact: true }).click()
    await expect(page.locator('.editor-save-state')).toHaveText('未保存')
    await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await leave.getByRole('button', { name: '放弃修改', exact: true }).click()
    await page.getByRole('button', { name: '查看文章：编辑测试', exact: true }).click()
    await append(page, '\n崩溃前内容')
    await expect(page.locator('.editor-footer')).toContainText('恢复记录已更新')
    // Destroy only this test window, bypassing normal close to simulate loss.
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].destroy())
    await app.close()
    app = await electron.launch({ args: [path.resolve('.')], env }); page = await app.firstWindow()
    page.on('pageerror', error => errors.push(error.message))
    await page.getByRole('button', { name: '查看文章：编辑测试', exact: true }).click()
    await page.getByRole('button', { name: '恢复到编辑器', exact: true }).click()
    await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await page.getByRole('button', { name: '保存并继续', exact: true }).click()
    await expect(page.getByRole('button', { name: '查看文章：编辑测试', exact: true })).toBeVisible()
    expect(await readFile(file, 'utf8')).toBe(saved + '来自外部编辑器\r\n崩溃前内容')
    expect(errors).toEqual([])
  } finally {
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())).catch(() => undefined)
    await app.close()
    if (path.resolve(root).startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(root).startsWith('astro-editor-e2e-')) await rm(root, { recursive: true, force: true })
  }
})

test('preview never executes article code; missing-file recovery can be exported', async ({}, testInfo) => {
  const root = await mkdtemp(path.join(tmpdir(), 'astro-editor-e2e-'))
  const blog = path.join(root, 'blog'), relative = 'src/contents/post/安全.mdx', file = path.join(blog, relative)
  await mkdir(path.dirname(file), { recursive: true }); await mkdir(path.join(blog, 'src/contents/ai-daily'), { recursive: true })
  await writeFile(path.join(blog, 'package.json'), JSON.stringify({ dependencies: { astro: '^5.3.0' } }))
  const source = '---\ntitle: 安全测试\npublished: 2026-01-01\n---\n# 安全预览\n\n<script>window.articleExecuted=true</script>\n\n<img src="https://example.invalid/pixel" onerror="window.articleExecuted=true" />\n\n![外部图片](https://example.invalid/pixel)\n\n[危险链接](javascript:alert(1))\n\n{window.articleExecuted=true}\n'
  await writeFile(file, source)
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((item): item is [string, string] => item[1] !== undefined)), ASTRO_DESKTOP_USER_DATA: path.join(root, 'profile') }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL
  const app = await electron.launch({ args: [path.resolve('.')], env })
  try {
    const page = await app.firstWindow(), requests: string[] = []
    page.on('request', request => { if (request.url().includes('example.invalid')) requests.push(request.url()) })
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, blog)
    await page.getByRole('button', { name: '选择博客目录', exact: true }).click()
    await page.getByRole('button', { name: '查看文章：安全测试', exact: true }).click()
    await page.getByRole('tab', { name: '预览', exact: true }).click()
    await expect(page.getByRole('heading', { name: '安全预览' })).toBeVisible()
    expect(await page.evaluate(() => 'articleExecuted' in window)).toBe(false)
    expect(await page.locator('.markdown-preview img, .markdown-preview script, .markdown-preview a').count()).toBe(0)
    expect(requests).toEqual([])
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 680))
    await page.screenshot({ path: testInfo.outputPath('editor-small-preview.png'), animations: 'disabled' })
    const doc = await page.evaluate(relative => window.astroDesktop!.readArticle(relative), relative)
    if (!doc.ok) throw new Error(doc.error)
    await page.evaluate(request => window.astroDesktop!.checkpointEditor(request), { projectPath: blog, relativePath: relative, source: source + '丢失文件恢复', baseRevision: doc.data.revision })
    await unlink(file)
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    // Refresh recovery index by reopening the project, just as a restart would.
    await page.getByRole('button', { name: '打开项目', exact: true }).click()
    await page.getByRole('button', { name: /恢复记录 \(/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: new RegExp(relative) }).click()
    await expect(page.getByLabel('恢复记录源码')).toHaveValue(source + '丢失文件恢复')
    await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true, filePath: '' }) })
    await page.getByRole('button', { name: '导出恢复副本', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('status')).toHaveCount(0)
    const destination = path.join(root, '恢复.mdx')
    await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }) }, destination)
    await page.getByRole('button', { name: '导出恢复副本', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('status')).toContainText('已写入')
    expect(await readFile(destination, 'utf8')).toBe(source + '丢失文件恢复')
    await page.getByRole('button', { name: '放弃此恢复记录', exact: true }).click()
    await page.getByRole('button', { name: '确认放弃这条记录', exact: true }).click()
    await expect(page.getByLabel('恢复记录源码')).toHaveCount(0)
  } finally {
    await app.close()
    if (path.resolve(root).startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(root).startsWith('astro-editor-e2e-')) await rm(root, { recursive: true, force: true })
  }
})
