import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, mkdir, writeFile, readdir, readFile, rename, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

test('create ordinary drafts through the desktop, preserve failures, and never offer daily creation', async ({}, testInfo) => {
  const temporary = await mkdtemp(path.join(tmpdir(), 'astro-draft-e2e-'))
  const blog = path.join(temporary, '中文 测试博客')
  const collection = path.join(blog, 'src/contents/post')
  await mkdir(collection, { recursive: true })
  await mkdir(path.join(blog, 'src/contents/ai-daily'), { recursive: true })
  await writeFile(path.join(blog, 'package.json'), JSON.stringify({ dependencies: { astro: '^5.3.0' } }))
  const existing = '---\ntitle: 已有文章\npublished: 2026-01-01\ncategory: 前端\ntags: [Astro]\n---\n保留正文\n'
  await writeFile(path.join(collection, '已有文章.md'), existing)
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), ASTRO_DESKTOP_USER_DATA: path.join(temporary, 'profile') }
  delete env.ELECTRON_RUN_AS_NODE
  delete env.ELECTRON_RENDERER_URL
  let app = await electron.launch({ args: [path.resolve('.')], env })
  try {
    let page = await app.firstWindow()
    const pageErrors: string[] = []
    page.on('pageerror', error => pageErrors.push(error.message))
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, blog)
    await page.getByRole('button', { name: '选择博客目录', exact: true }).click()
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    let modal = page.getByRole('dialog', { name: '创建新文章' })
    await expect(modal.getByLabel('文章标题')).toBeFocused()
    await expect(modal.getByRole('button', { name: '创建草稿', exact: true })).toBeDisabled()
    await modal.getByLabel('文章标题').fill('   ')
    await expect(modal.getByRole('button', { name: '创建草稿', exact: true })).toBeDisabled()
    await modal.getByRole('button', { name: '取消', exact: true }).click()
    expect(await readdir(collection)).toEqual(['已有文章.md'])
    await expect(page.getByRole('button', { name: '新建文章', exact: true })).toBeFocused()
    // Ensure a hidden-by-filter new draft becomes visible and selected after creation.
    await page.getByLabel('搜索文章', { exact: true }).fill('没有匹配的文章')
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    await modal.getByLabel('文章标题').fill('Windows: Astro 新文章')
    await modal.getByLabel('标签', { exact: true }).fill('Astro')
    await modal.getByLabel('标签', { exact: true }).press('Enter')
    await expect(modal.getByRole('button', { name: '移除标签：Astro' })).toBeVisible()
    await modal.getByLabel('标签', { exact: true }).fill('未回车标签')
    await modal.getByLabel('分类', { exact: false }).fill('前端')
    await modal.getByLabel('摘要', { exact: false }).fill('真实写入的草稿\n保留第二行')
    await page.screenshot({ path: testInfo.outputPath('create-draft-light.png') })
    await modal.getByRole('button', { name: '创建草稿', exact: true }).click()
    await expect(modal).not.toBeVisible()
    await expect(page).toHaveURL(/#\/library\/drafts$/)
    await expect(page.locator('.created-banner')).toContainText('草稿已创建')
    await expect(page.getByRole('region', { name: '文章编辑工作区', exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: '文章属性', exact: true })).toContainText('未回车标签')
    const filename = 'Windows- Astro 新文章.md'
    const source = await readFile(path.join(collection, filename), 'utf8')
    expect(source).toContain('draft: true')
    expect(source).toContain('category: "前端"')
    expect(source).toContain('tags: ["Astro","未回车标签"]')
    expect(await readFile(path.join(collection, '已有文章.md'), 'utf8')).toBe(existing)
    await page.getByRole('button', { name: '刷新文章', exact: true }).click()
    await expect(page.locator('.editor-heading-title')).toContainText('Windows: Astro 新文章')
    await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    await modal.getByLabel('文章标题').fill('Windows: Astro 新文章')
    await page.screenshot({ path: testInfo.outputPath('create-draft-dark.png') })
    // Make the directory unavailable to exercise the real write failure, then retry.
    await rename(collection, `${collection}-held`)
    await modal.getByRole('button', { name: '创建草稿', exact: true }).click()
    await expect(modal.getByRole('alert')).toBeVisible()
    await expect(modal.getByLabel('文章标题')).toHaveValue('Windows: Astro 新文章')
    await rename(`${collection}-held`, collection)
    await modal.getByRole('button', { name: '创建草稿', exact: true }).click()
    await expect(modal).not.toBeVisible()
    await expect(page.locator('.article-row')).toHaveCount(2)
    expect(await readFile(path.join(collection, filename), 'utf8')).toBe(source)
    expect(await readdir(collection)).toContain('Windows- Astro 新文章-2.md')
    await page.locator('a[href="#/library/daily"]').click()
    await expect(page.getByRole('button', { name: '新建文章', exact: true })).toHaveCount(0)
    const invalid = await page.evaluate((projectPath) => window.astroDesktop!.createDraft({ projectPath, title: '禁止新增日报', category: '', tags: [], description: '', kind: 'ai-daily' } as never), blog)
    expect(invalid).toMatchObject({ ok: false, code: 'INVALID_DRAFT' })
    expect(await readdir(path.join(blog, 'src/contents/ai-daily'))).toEqual([])
    await app.close()
    app = await electron.launch({ args: [path.resolve('.')], env })
    page = await app.firstWindow()
    await page.locator('a[href="#/library/drafts"]').click()
    await expect(page.locator('.article-row')).toHaveCount(2)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 680))
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    modal = page.getByRole('dialog', { name: '创建新文章' })
    await expect(modal).toBeVisible()
    await modal.getByRole('button', { name: '取消', exact: true }).scrollIntoViewIfNeeded()
    await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath('create-draft-small-window.png') })
    await page.keyboard.press('Escape')
    await expect(modal).not.toBeVisible()
    expect(pageErrors).toEqual([])
  } finally {
    await app.close()
    const target = path.resolve(temporary)
    if (target.startsWith(path.resolve(tmpdir()) + path.sep) && path.basename(target).startsWith('astro-draft-e2e-')) await rm(target, { recursive: true, force: true })
  }
})
